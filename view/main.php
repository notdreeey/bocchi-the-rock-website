          <h2>Bocchi the Rock!</h2>
          <h3>ぼっち・ざ・ろっく!</h3>
          <p>Manga/Anime TV Series</p>
        </div>
        <p style="text-align:justify;">Bocchi the Rock! (ぼっち・ざ・ろっく！, Botchi Za Rokku!) is a Japanese four-panel manga
          series written and illustrated by Aki Hamaji. It has been serialized in Houbunsha's seinen manga magazine
          Manga Time Kirara Max since December 2017. Its chapters have been collected in six tankōbon volumes as of
          August 2023. A spin-off manga series, titled Bocchi the Rock! Gaiden: Hiroi Kikuri no Fukazake Nikki, began
          publication in July 2023.</p>

        <p style="text-align:justify;">An anime television series adaptation produced by CloverWorks aired from October
          to December 2022. Both the manga and the anime received widespread acclaim for the animation, writing, voice
          acting, comedy, characters, music, and exploration of social anxiety.</p>

        <p style="text-align:justify;">Extremely anxious and socially awkward Hitori Gotoh longs to become a rock
          musician in spite of her struggles, while fulfilling her desires to one day make friends. She is suddenly
          given a chance to do so after she is taken in by another girl, Nijika Ijichi, to become a member of her newly
          formed Kessoku Band.</p>
